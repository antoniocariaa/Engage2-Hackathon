"""Exit-coordination report (EXIT_COORDINATION_PROMPT.md): per-run overall/per-type top-3 and the adoption check.

  python -m src.xc_report <reference> <run> [<run> ...]      -> reports/exit_coordination.md
Runs are names of cache/preds/<name>.npz files holding CV out-of-fold ('oof') and train-only validation ('val') scores.
"""
from __future__ import annotations

import sys

import numpy as np
import pandas as pd

from src.cv import controller_folds, fold_array
from src.data_io import ROOT, TASK_TYPES, load_all, load_config
from src.metrics import hits_from_scores, paired_session_bootstrap, true_rank
from src.rank import within_sample_z

PRED = ROOT / "cache" / "preds"
TYPES = [3, 5, 4, 12, 2, 10]
SHORT = {3: "exit_coord", 5: "transfer", 4: "assume", 12: "zone", 2: "entry_coord", 10: "exit_cond"}
HYP = {
    "lgb_lambdarank_rw5_xc_3s": "Causal: coordination is needed when the agreed exit level no longer matches the "
                                "cleared level, after a recent level clearance.",
    "lgb_lambdarank_rw5_xcl_3s": "Causal + forward-looking: the task being coordinated shows a coordination-state "
                                 "change, a clearance or a controller input on the aircraft shortly afterwards.",
    "lgb_binary_xcl_3s": "Same features as xcl on the binary objective, as a blend component.",
}


def per_sample_type(df: pd.DataFrame) -> pd.Series:
    return df.loc[df["target_index"] == 1].set_index("sample_id")["task_index"]


def evaluate(name: str, tr, va, sfold) -> dict:
    p = np.load(PRED / f"{name}.npz")
    ho, hv = hits_from_scores(tr, p["oof"]), hits_from_scores(va, p["val"])
    to, tv = per_sample_type(tr).reindex(ho.index), per_sample_type(va).reindex(hv.index)
    folds = [float(ho[sfold.reindex(ho.index).to_numpy() == k].mean()) for k in range(4)]
    r = dict(name=name, cv=float(np.mean(folds)), cv_std=float(np.std(folds, ddof=1)), folds=folds, val=float(hv.mean()),
             ho=ho, hv=hv)
    for t in TYPES:
        r[f"cv_{t}"], r[f"val_{t}"] = float(ho[to == t].mean()), float(hv[tv == t].mean())
    return r


def diagnosis(tr, va, name: str) -> list[str]:
    p = np.load(PRED / f"{name}.npz")
    lines = []
    for lab, df, sc in (("CV", tr, p["oof"]), ("validation", va, p["val"])):
        z = within_sample_z(df, sc)
        tt = per_sample_type(df)
        row_tt = df["sample_id"].map(tt).to_numpy()
        ti = df["task_index"].to_numpy()
        h = hits_from_scores(df, z)
        o_all = hits_from_scores(df, z + 100.0 * (ti == row_tt)).mean()
        o_3 = hits_from_scores(df, z + 100.0 * ((ti == row_tt) & (row_tt == 3))).mean()
        rk = true_rank(df, sc)
        is3 = tt.reindex(rk.index).to_numpy() == 3
        d3 = df.loc[ti == 3, ["sample_id", "target_index"]].assign(s=np.asarray(sc)[ti == 3])
        d3["rk"] = d3.groupby("sample_id")["s"].rank(ascending=False, method="first")
        t3 = d3[d3["target_index"] == 1]
        lines.append(f"| {lab} | {h.mean():.4f} | {int(is3.sum())} | {h[tt.reindex(h.index) == 3].mean():.3f} | "
                     f"{np.median(rk[is3]):.0f} | {(t3.rk == 1).mean():.3f} | {(t3.rk <= 3).mean():.3f} | "
                     f"{o_all:.4f} | {o_3:.4f} |")
    return lines


def main(names: list[str]) -> None:
    cfg = load_config()
    d = load_all(cfg)
    tr, va = d["train"], d["validation"]
    folds = fold_array(tr, controller_folds(tr, cfg["n_folds"]))
    sfold = pd.Series(folds, index=tr["sample_id"].to_numpy()).groupby(level=0).first()
    ref_name = names[0]
    ref = evaluate(ref_name, tr, va, sfold)
    tsess = tr.groupby("sample_id")["session"].first()
    vsess = va.groupby("sample_id")["session"].first()
    out = ["# Exit coordination (task_index 3)", "",
           "Generated by `python -m src.xc_report " + " ".join(names) + "`. CV = 4 leave-controller-out folds on "
           "train (out-of-fold, 3 seeds); validation = train-only fit scored once.", "",
           f"## Step 0: diagnosis of the reference `{ref_name}`", "",
           "| split | overall top-3 | exit-coord targets | exit-coord top-3 | median rank of true row | true row best "
           "type-3 row | true row in 3 best type-3 rows | oracle: type known for all | oracle: type known for "
           "exit-coord only |", "|---|---|---|---|---|---|---|---|---|"]
    out += diagnosis(tr, va, ref_name)
    out += ["", "## Runs", "",
            "Adoption: overall CV mean improves, at least 3 of 4 folds improve, validation drops by at most 0.01. "
            "Δ and folds are against the reference; CI is a paired session-block bootstrap on CV out-of-fold hits.", "",
            "| run | CV mean ± std | folds | val | " + " | ".join(f"{SHORT[t]} CV / val" for t in TYPES) +
            " | Δ CV [95% CI] | folds better | Δ val | decision |",
            "|---|---|---|---|" + "---|" * len(TYPES) + "---|---|---|---|"]
    for n in names:
        r = ref if n == ref_name else evaluate(n, tr, va, sfold)
        typ = " | ".join(f"{r[f'cv_{t}']:.3f} / {r[f'val_{t}']:.3f}" for t in TYPES)
        if n == ref_name:
            cmp, dec = "— | — | — ", "reference"
        else:
            dcv = r["cv"] - ref["cv"]
            nb = sum(a > b for a, b in zip(r["folds"], ref["folds"]))
            dv = r["val"] - ref["val"]
            _, lo, hi, _ = paired_session_bootstrap(r["ho"], ref["ho"], tsess)
            ok = dcv > 0 and nb >= 3 and dv >= -0.01
            cmp, dec = f"{dcv:+.4f} [{lo:+.4f},{hi:+.4f}] | {nb}/4 | {dv:+.4f} ", "**adopt**" if ok else "reject"
            print(f"{n}: CV {r['cv']:.4f} (Δ {dcv:+.4f}, {nb}/4 folds) val {r['val']:.4f} (Δ {dv:+.4f}) "
                  f"exit_coord CV {r['cv_3']:.3f} val {r['val_3']:.3f} -> {dec}")
        out.append(f"| `{n}` | {r['cv']:.4f} ± {r['cv_std']:.4f} | {'/'.join(f'{x:.4f}' for x in r['folds'])} | "
                   f"{r['val']:.4f} | {typ} | {cmp}| {dec} |")
    out += ["", "## Hypotheses", ""] + [f"- `{n}`: {HYP[n]}" for n in names if n in HYP]
    (ROOT / "reports" / "exit_coordination.md").write_text("\n".join(out) + "\n")
    print("wrote reports/exit_coordination.md")


if __name__ == "__main__":
    main(sys.argv[1:])
